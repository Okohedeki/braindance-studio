"""Package a completion run (complete_difix.py) as a viewer scene.

Exports the filled checkpoint the same way as the scene it was filled from
(same frames, clip order, rasterisation), measures its free space, labels the
filled content as inferred, sets how high the viewer lets the camera go, and
places any objects already tracked for these clips.

  python package_filled.py --run run_house-roam --base house-filled2 --out house-roam --max-rise 0.9 \\
      --note "filled by complete_difix.py --cameras roam anywhere in the free space, floor to ceiling"

Run with the reconstruction environment.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent


def run(*cmd):
    print("$", " ".join(map(str, cmd)), flush=True)
    subprocess.run([sys.executable, *map(str, cmd)], cwd=HERE, check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True, help="completion run folder under work/<base scene>/")
    ap.add_argument("--base", required=True, help="viewer package the run was filled from")
    ap.add_argument("--out", required=True, help="new viewer package name")
    ap.add_argument("--max-rise", type=float, required=True,
                    help="how far above the recording height the viewer lets the camera go (fraction of floor-to-ceiling)")
    ap.add_argument("--note", default="", help="what the fill covered, for scene.json")
    ap.add_argument("--voxels", type=int, default=320)
    args = ap.parse_args()

    work_name = args.base.split("-")[0]
    work = HERE / "work" / work_name
    base = json.loads((HERE / "viewer" / args.base / "scene.json").read_text())
    clips = list(dict.fromkeys(f["clip"] for f in base["frames"]))
    # Same timeline as the base: source frame step from its first two frames,
    # rate from the first clip's last frame (times are rounded to 0.1 ms),
    # snapped to a standard video rate.
    first = [f for f in base["frames"] if f["clip"] == clips[0]]
    frame_step = first[1]["sourceFrame"] - first[0]["sourceFrame"]
    estimate = first[-1]["sourceFrame"] / first[-1]["time"]
    rates = [23.976, 24, 25, 29.97, 30, 48, 50, 59.94, 60]
    source_fps = min(rates, key=lambda r: abs(r - estimate))
    if abs(source_fps - estimate) > 0.001 * estimate:
        source_fps = estimate
    source = base["source"]
    if "filled by Difix3D+" not in source:
        source += "; unseen views filled by Difix3D+"

    out = HERE / "viewer" / args.out
    run("export_for_viewer.py", "--data-dir", work / "train", "--ckpt", work / args.run / "ckpts" / "ckpt_filled.pt",
        "--frames", work / "images", "--out", out, "--rasterization", base.get("rasterization", "classic"),
        "--primitive", base.get("primitive", "3dgs"), "--source", source, "--frame-step", frame_step,
        "--source-fps", source_fps, "--clips", *clips)
    run("free_space.py", "--scene", args.out, "--voxels", args.voxels)

    meta = json.loads((out / "scene.json").read_text())
    same = len(meta["frames"]) == len(base["frames"]) and all(
        a["name"] == b["name"] and a["sourceFrame"] == b["sourceFrame"] and abs(a["time"] - b["time"]) < 1e-3
        and a["c2w"] == b["c2w"] for a, b in zip(meta["frames"], base["frames"]))
    if not same:
        raise SystemExit("exported frames differ from the base scene's; check the export options")
    meta["provenance"]["inferred"] = (
        "views the recording never saw were generated by Difix3D+ from rendered views and baked into the "
        "splats; content there is a guess")
    # Splats added for what the recording never saw (unseen_bake.py), flagged one byte per splat.
    flags = work / args.run / "inferred.npy"
    if flags.exists():
        inferred = np.load(flags).astype(np.uint8)
        if len(inferred) != meta["splatCount"]:
            raise SystemExit("inferred.npy doesn't match the exported splats")
        (out / "inferred.bin").write_bytes(inferred.tobytes())
        meta["inferred"] = {"file": "inferred.bin", "count": int(inferred.sum()),
                            "method": "SEVA views of what the recording never saw, lifted into new splats with "
                                      "MoGe-2 depth (unseen_generate.py, unseen_bake.py)"}
        meta["provenance"]["inferred"] += ("; splats flagged in inferred.bin were added for surfaces no frame "
                                           "showed: SEVA's guess, not a reconstruction")
    meta["navigation"] = {"maxRise": args.max_rise, "note": args.note}
    (out / "scene.json").write_text(json.dumps(meta, indent=1))

    if list((work / "objects" / "tracks").glob("*/tracks.json")):
        run("lift_objects.py", "--scene", args.out, "--work", work_name)
    print(f"packaged {out}")


if __name__ == "__main__":
    main()
